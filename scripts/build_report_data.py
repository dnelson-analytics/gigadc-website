"""Build js/reports/supply-and-demand-data.js for the Supply and Demand report page.

Usage: python scripts/build_report_data.py [path-to-gigadc-reporting]

A port of the Power Query in the Supply and Demand semantic model (ADR 0002):
the Delivery MW query (Supply Date, Delivery Status) and the Supply query
(region x month on Demand's grid, running totals, rounding, Net Supply).
Keep it in step with those queries. Run `python -m generator` in
gigadc-reporting first on a fresh clone.
"""
import csv
import json
import sys
from datetime import date, timedelta
from pathlib import Path

AS_OF = date(2026, 9, 30)  # the reports' default As Of Date parameter

root = Path(sys.argv[1] if len(sys.argv) > 1 else "../gigadc-reporting")
site = Path(__file__).resolve().parent.parent


def rows(rel):
    with open(root / rel, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def round1(x):
    """Number.Round(x, 1) as Power Query computes it: x * 10 rounded half to
    even on the double, then / 10 (ADR 0001, reconciled against the model)."""
    return round(x * 10) / 10


factor = float(rows("reference/model_parameters.csv")[0]["net_supply_factor"])

# Hierarchy: Areas and Regions with their sort orders.
hierarchy = rows("reference/hierarchy.csv")
region_of = {h["data_center_code"]: h["region"] for h in hierarchy}
regions = {}
for h in hierarchy:
    regions[h["region"]] = {"area": h["area"], "areaSort": int(h["area_sort"]),
                            "sort": int(h["region_sort"])}
region_names = sorted(regions, key=lambda r: (regions[r]["areaSort"], regions[r]["sort"]))
areas = sorted({regions[r]["area"] for r in regions},
               key=lambda a: min(regions[r]["areaSort"] for r in regions if regions[r]["area"] == a))

# Demand: the region x month grid Supply is built on.
demand = {(r["region"], r["month_start"][:7]): float(r["demand_mw"])
          for r in rows("generator/out/demand.csv")}
months = sorted({m for _, m in demand})

# Delivery MW: one row per building, from its Building Ready row.
buildings = []
for d in rows("generator/out/deliveries.csv"):
    if d["milestone"] != "Building Ready":
        continue
    plan, actual = date.fromisoformat(d["planned_date"]), date.fromisoformat(d["actual_date"])
    status = "Delivered" if actual <= AS_OF else "To Be Delivered"
    if status == "Delivered":
        supply_date = actual
    elif plan > AS_OF:
        supply_date = plan
    else:
        supply_date = AS_OF + timedelta(days=1)       # late: held to the day after As Of
    buildings.append({"building": d["building_code"], "dataCenter": d["data_center_code"],
                      "region": region_of[d["data_center_code"]], "mw": float(d["mw"]),
                      "supplyDate": supply_date.isoformat(), "status": status})
buildings.sort(key=lambda b: (b["supplyDate"], b["building"]))

# Supply: additions by region x month on Demand's grid (later months drop out),
# accumulated, rounded to 0.1, then Net Supply = round(Supply x factor).
series = {}
for reg in region_names:
    added = {m: [0.0, 0.0, 0.0] for m in months}      # all, delivered, to be delivered
    for b in buildings:
        m = b["supplyDate"][:7]
        if b["region"] == reg and m in added:
            added[m][0] += b["mw"]
            added[m][1 if b["status"] == "Delivered" else 2] += b["mw"]
    total = [0.0, 0.0, 0.0]
    supply, net, delivered, to_be, dem = [], [], [], [], []
    for m in months:
        total = [t + a for t, a in zip(total, added[m])]
        s = round1(total[0])
        supply.append(s)
        net.append(round1(s * factor))
        delivered.append(round1(total[1]))
        to_be.append(round1(total[2]))
        dem.append(demand[(reg, m)])
    series[reg] = {"supply": supply, "netSupply": net, "deliveredSupply": delivered,
                   "toBeDeliveredSupply": to_be, "demand": dem}

data = {
    "asOf": AS_OF.isoformat(),
    "netSupplyFactor": factor,
    "months": months,
    "areas": areas,
    "regions": [{"name": r, "area": regions[r]["area"]} for r in region_names],
    "series": series,
    "buildings": buildings,
}
out = site / "js" / "reports" / "supply-and-demand-data.js"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("// Generated by scripts/build_report_data.py. Do not edit.\n"
               "window.SUPPLY_DEMAND_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n",
               encoding="utf-8")
print(f"wrote {out} ({out.stat().st_size:,} bytes): {len(months)} months "
      f"{months[0]}..{months[-1]}, {len(region_names)} regions, {len(buildings)} buildings")
