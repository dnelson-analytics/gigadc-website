"""Build js/reports/capacity-delivery-data.js for the Capacity Delivery report page.

Usage: python scripts/build_delivery_data.py [path-to-gigadc-reporting]

A port of the Power Query in the Capacity Delivery semantic model (ADR 0002):
the Delivery query (milestones from reference/milestones.csv, Drift, Status,
Status Score, Status Weight) and the Delivery MW query (one row per building,
Delivery Status). Keep it in step with those queries. Run `python -m generator`
in gigadc-reporting first on a fresh clone.
"""
import csv
import json
import sys
from datetime import date
from pathlib import Path

AS_OF = date(2026, 9, 30)  # the reports' default As Of Date parameter

root = Path(sys.argv[1] if len(sys.argv) > 1 else "../gigadc-reporting")
site = Path(__file__).resolve().parent.parent


def rows(rel):
    with open(root / rel, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


# Milestones, in sort order: name, short label, description.
milestones = sorted(rows("reference/milestones.csv"), key=lambda m: int(m["milestone_sort"]))
sort_of = {m["milestone"]: int(m["milestone_sort"]) for m in milestones}
weight = 1 / len(milestones)                     # one milestone's share of its building

# Hierarchy: Area -> Region -> Data Center, with sort orders.
hierarchy = sorted(rows("reference/hierarchy.csv"),
                   key=lambda h: (int(h["area_sort"]), int(h["region_sort"]), h["data_center_code"]))
regions, data_centers = [], []
for h in hierarchy:
    if h["region"] not in [r["name"] for r in regions]:
        regions.append({"name": h["region"], "area": h["area"]})
    data_centers.append({"code": h["data_center_code"], "region": h["region"], "area": h["area"]})
areas = list(dict.fromkeys(h["area"] for h in hierarchy))
region_of = {d["code"]: d["region"] for d in data_centers}


def status(plan, actual):
    """Delivery's Status column (ADR 0008, section 7): can we trust this date?"""
    drift = (actual - plan).days
    if actual <= AS_OF:
        return "Grey"
    if plan < AS_OF or drift > 30:
        return "Red"
    if drift >= 1:
        return "Amber"
    return "Green"


# Delivery: one row per building per milestone. Delivery MW: one row per building.
by_building = {}
for d in rows("generator/out/deliveries.csv"):
    code = d["building_code"]
    if d["milestone"] not in sort_of:
        raise ValueError(f"deliveries.csv has a milestone that is not in milestones.csv: {d['milestone']}")
    b = by_building.setdefault(code, {"building": code, "dataCenter": d["data_center_code"],
                                      "region": region_of[d["data_center_code"]],
                                      "milestones": [None] * len(milestones)})
    plan, actual = date.fromisoformat(d["planned_date"]), date.fromisoformat(d["actual_date"])
    b["milestones"][sort_of[d["milestone"]] - 1] = [
        plan.isoformat(), actual.isoformat(), (actual - plan).days, status(plan, actual)]
    if d["milestone"] == "Building Ready":
        b["mw"] = float(d["mw"])
        b["planDate"], b["actualDate"] = plan.isoformat(), actual.isoformat()
        b["deliveryStatus"] = "Delivered" if actual <= AS_OF else "To Be Delivered"

buildings = sorted(by_building.values(), key=lambda b: b["building"])

data = {
    "asOf": AS_OF.isoformat(),
    "statusWeight": weight,
    "milestones": [{"name": m["milestone"], "label": m["short_label"], "description": m["description"]}
                   for m in milestones],
    "areas": areas,
    "regions": regions,
    "dataCenters": data_centers,
    # milestones[i] = [plan, actual / forecast, drift (days), status], or null
    # where the building has no such row (the operating base has Building Ready only).
    "buildings": buildings,
}
out = site / "js" / "reports" / "capacity-delivery-data.js"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("// Generated by scripts/build_delivery_data.py. Do not edit.\n"
               "window.CAPACITY_DELIVERY_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n",
               encoding="utf-8")
open_rows = sum(1 for b in buildings for m in b["milestones"] if m and m[3] != "Grey")
print(f"wrote {out} ({out.stat().st_size:,} bytes): {len(buildings)} buildings, "
      f"{len(data_centers)} data centers, {open_rows} open milestone rows")
